#!/usr/bin/env node
/*
 * Derives css/cte-glow-legacy.css: for every rule in the older stylesheets that
 * hard-codes a light-shell colour, emit the same selector with the colour moved
 * onto the black-and-gold scale. Only colour declarations are emitted; layout is
 * never touched. Re-run after editing any source sheet:
 *   node tools/theme/build-glow-legacy.cjs
 * Hand-written theme rules live in css/cte-glow.css, which loads after this file.
 */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', '..');
const SOURCES = ['network-v29.css', 'league-extras-v33.css', 'taste-v40.css', 'css/cte-homepage.css', 'css/cte-explore.css', 'css/cte-navigation.css', 'css/cte-quality.css', 'install-card-v36.css'];
const PROPS = /^(color|background|background-color|background-image|border|border-(top|right|bottom|left|color|block|inline)(-color)?|outline|outline-color|fill|stroke|box-shadow|text-decoration-color|caret-color|accent-color|-webkit-text-fill-color|-webkit-text-stroke)$/;
const GOLD = '#e6b84a', GOLD_BRIGHT = '#f6d57a', ON_GOLD = '#171204';

function hsl(r, g, b) { r /= 255; g /= 255; b /= 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2; let h = 0, s = 0; if (mx !== mn) { const d = mx - mn; s = l > .5 ? d / (2 - mx - mn) : d / (mx + mn); h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h *= 60; } return [h, s, l]; }
function parseHex(x) { let h = x.slice(1); if (h.length === 3 || h.length === 4) h = [...h].map(c => c + c).join(''); return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16), h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1]; }
const withAlpha = (hex, a) => a >= .995 ? hex : `rgba(${parseHex(hex).slice(0, 3).join(',')},${Math.round(a * 100) / 100})`;

// role: 'text' | 'bg' | 'line'
function map(r, g, b, a, role) {
  const [h, s, l] = hsl(r, g, b);
  const out = hex => withAlpha(hex, a);
  if (s < .2 || l > .97 || l < .06 || Math.max(r, g, b) - Math.min(r, g, b) < 14) { // neutrals
    if (role === 'text') return l < .32 ? out('#f4f1ea') : l < .5 ? out('#aab0ba') : l < .72 ? out('#9aa1ac') : null;
    if (role === 'line') return l > .6 ? out('#2a2e36') : l > .3 ? out('#3a3f49') : null;
    if (role === 'shadow') return null;
    return l >= .985 ? out('#131519') : l >= .9 ? out('#1a1d23') : l >= .7 ? out('#2a2e36') : l >= .3 ? out('#3a3f49') : null;
  }
  const red = h < 22 || h > 335, green = h > 95 && h < 175, blue = h >= 175 && h < 260, warm = h >= 22 && h <= 60;
  if (red) {
    if (l >= .86) return role === 'text' ? null : role === 'line' ? out('#6b5520') : withAlpha(GOLD, .12 * a);
    if (role === 'text') return out(l > .62 ? GOLD_BRIGHT : GOLD);
    if (role === 'shadow') return withAlpha(GOLD, Math.min(a, .35));
    if (l < .3 && s < .5) return null; // deep maroon surfaces on dark cards stay
    return out(GOLD);
  }
  if (green) return l >= .8 ? (role === 'text' ? null : withAlpha('#62d896', .14 * a)) : role === 'bg' && l < .45 ? out('#1f7a4d') : out('#62d896');
  if (blue) return l >= .8 ? (role === 'text' ? null : withAlpha('#8fb8ff', .14 * a)) : role === 'text' || role === 'line' ? out(l < .5 ? '#8fb8ff' : '#b9d2ff') : null;
  if (warm) return l >= .8 ? (role === 'text' ? null : withAlpha(GOLD, .14 * a)) : role === 'text' ? out('#f2c46b') : null;
  return null;
}
const COLOR = /\bwhite\b|\bblack\b|#[0-9a-fA-F]{3,8}\b|rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*(?:,\s*[\d.]+\s*)?\)/g;
function convert(prop, value) {
  const role = /^(color|fill|stroke|caret-color|-webkit-text)/.test(prop) ? 'text' : /^(border|outline|text-decoration)/.test(prop) ? 'line' : prop === 'box-shadow' ? 'shadow' : 'bg';
  let changed = false;
  const next = value.replace(COLOR, m => {
    if (m === 'white') m = '#ffffff'; if (m === 'black') m = '#000000';
    const [r, g, b, a] = m[0] === '#' ? parseHex(m) : (x => [x[0], x[1], x[2], x[3] ?? 1])(m.match(/[\d.]+/g).map(Number));
    const to = map(r, g, b, a, role);
    if (!to) return m; changed = true; return to;
  });
  return changed ? next : null;
}
function rules(css, emit, wrap = []) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i); if (open < 0) break;
    const sel = css.slice(i, open).trim(); let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const bodyText = css.slice(open + 1, j - 1);
    if (/^@(media|supports|layer|container)/.test(sel)) rules(bodyText, emit, [...wrap, sel]);
    else if (!sel.startsWith('@')) emit(sel, bodyText, wrap);
    i = j;
  }
}
let out = '/* GENERATED by tools/theme/build-glow-legacy.cjs — do not edit by hand.\n * Colour-only overrides that move the light-shell rules onto the black-and-gold scale. */\n';
let count = 0;
for (const file of SOURCES) {
  const chunks = [];
  rules(fs.readFileSync(path.join(root, file), 'utf8'), (sel, bodyText, wrap) => {
    const decls = [], seen = bodyText.split(/;(?![^(]*\))/).map(d => d.trim()).filter(Boolean).map(d => { const k = d.indexOf(':'); return [d.slice(0, k).trim().toLowerCase(), d.slice(k + 1).trim()]; });
    let goldBg = false, hasColor = false;
    for (const [prop, value] of seen) {
      if (/^--/.test(prop) || !PROPS.test(prop)) continue;
      if (prop === 'color') hasColor = true;
      if (/^background(-color)?$/.test(prop) && /^var\(--(n-red|t-red|t-red-deep|gold|gold2|cte2-accent|cte2-accent-strong)\b[^)]*\)\s*(!important)?$/.test(value)) goldBg = true;
      const v = convert(prop, value);
      if (v) { decls.push(prop + ':' + v); if (/^background(-color)?$/.test(prop) && v.includes(GOLD) && !/rgba/.test(v) && !/gradient/.test(v)) goldBg = true; }
    }
    if (goldBg) { const i = decls.findIndex(d => d.startsWith('color:')); if (i >= 0) decls.splice(i, 1); decls.push('color:' + ON_GOLD + (seen.some(([p, v]) => p === 'color' && /!important/.test(v)) ? '!important' : '')); }
    if (!decls.length) return;
    const scoped = sel.split(',').map(s => s.trim()).map(s => /^(html|:root)\b/.test(s) ? s : 'html ' + s).join(',');
    chunks.push(wrap.map(w => w + '{').join('') + scoped + '{' + decls.join(';') + '}' + '}'.repeat(wrap.length)); count++;
  });
  if (chunks.length) out += '\n/* ' + file + ' */\n' + chunks.join('\n') + '\n';
}
fs.writeFileSync(path.join(root, 'css', 'cte-glow-legacy.css'), out);
console.log('css/cte-glow-legacy.css: ' + count + ' rules, ' + out.length + ' bytes');

#!/usr/bin/env python3
"""Build link previews for the State of the Union and each of its sections.

Writes sotu/<section>.html (Open Graph tags + redirect to
state-of-the-union.html#<section>) and sotu/<section>.jpg (1200x630 card drawn
with the same renderer as tools/share/build-share-cards.py). Kept in sotu/ so
the article share check, which treats every file in share/ as an article, is
unaffected.

  python3 tools/share/build-sotu-cards.py          # (re)build pages; cards only if missing
  python3 tools/share/build-sotu-cards.py --force  # re-render cards too
  python3 tools/share/build-sotu-cards.py --check  # fail if anything is missing or stale

Post sotu/<section>.html links on Facebook, not the #anchor URL: crawlers never see anchors.
"""
import html
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("share_cards", os.path.join(HERE, "build-share-cards.py"))
cards = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cards)
OUT = os.path.join(cards.ROOT, "sotu")
SITE = cards.SITE
KICKER = "CTE State of the Union"
SECTIONS = [
    ("state-of-the-union", "", "State of the Union", "Every champion, every trade and what became of it, every franchise's story. Live from Sleeper."),
    ("state", "state", "CTE Bot's read on the league", "The headlines, straight from the numbers. Nobody is innocent."),
    ("history", "history", "Banners, runners-up and the Toilet Bowl", "Every season's champion, runner-up, regular-season winner and last place."),
    ("trades", "trades", "Every trade, and what became of it", "Trade trees for every deal in league history, and who is winning each one."),
    ("franchises", "franchises", "Twelve franchises, how they got here", "Records, roster cores and how every team was built, season by season."),
    ("records", "records", "The CTE record book", "All-time standings, luck, blowouts, nail-biters, traders and drafters."),
]


def page(slug, anchor, title, desc):
    target = "../state-of-the-union.html" + ("#" + anchor if anchor else "")
    canonical = SITE + "state-of-the-union.html" + ("#" + anchor if anchor else "")
    t, d = html.escape(title + " • CTE State of the Union" if anchor else "CTE State of the Union", quote=True), html.escape(desc, quote=True)
    img = f"{SITE}sotu/{slug}.jpg"
    return f"""<!DOCTYPE html>
<!-- Generated by tools/share/build-sotu-cards.py. Do not edit by hand. -->
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{t} • CTE Network</title>
<meta name="description" content="{d}">
<link rel="canonical" href="{canonical}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="CTE Network">
<meta property="og:title" content="{t}">
<meta property="og:description" content="{d}">
<meta property="og:url" content="{SITE}sotu/{slug}.html">
<meta property="og:image" content="{img}">
<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">
<meta property="og:image:alt" content="{t}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{t}">
<meta name="twitter:description" content="{d}">
<meta name="twitter:image" content="{img}">
<meta http-equiv="refresh" content="0; url={target}">
<script>location.replace({json.dumps(target)});</script>
<style>body{{font:16px system-ui,-apple-system,sans-serif;background:#0b0c0f;color:#f5f3ee;display:grid;place-items:center;min-height:100vh;margin:0}}a{{color:#f2cf74}}</style>
</head><body><main><h1>{t}</h1><p><a href="{target}">Open on CTE Network →</a></p></main></body></html>
"""


def main():
    check, force = "--check" in sys.argv, "--force" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    problems = []
    for slug, anchor, title, desc in SECTIONS:
        hp, ip = os.path.join(OUT, slug + ".html"), os.path.join(OUT, slug + ".jpg")
        want = page(slug, anchor, title, desc)
        if check:
            if not os.path.exists(hp) or open(hp, encoding="utf-8").read() != want:
                problems.append(f"stale/missing sotu/{slug}.html")
            if not os.path.exists(ip):
                problems.append(f"missing sotu/{slug}.jpg")
            continue
        with open(hp, "w", encoding="utf-8") as f:
            f.write(want)
        if force or not os.path.exists(ip):
            cards.card(KICKER, title, desc, "LIVE FROM SLEEPER · PRESENTED BY SHOW ME INDUSTRIES", ip)
    if check:
        print("\n  ".join(["State of the Union previews out of date — run: python3 tools/share/build-sotu-cards.py"] + problems) if problems else f"PASS: {len(SECTIONS)} State of the Union share pages and cards are current")
        return 1 if problems else 0
    print(f"Built {len(SECTIONS)} State of the Union share pages in sotu/")
    return 0


if __name__ == "__main__":
    sys.exit(main())

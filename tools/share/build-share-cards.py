#!/usr/bin/env python3
"""Build Facebook/iMessage link previews for CTE Network.

For every newsroom article this writes:
  share/<id>.html  - tiny page with Open Graph + Twitter tags that forwards
                     readers to article.html?id=<id> (crawlers don't run JS,
                     so article.html?id=... alone can't have per-story tags)
  share/<id>.jpg   - 1200x630 headline card in league colours
plus share/cte-network.jpg, the default card used by every other page.

Usage
  python3 tools/share/build-share-cards.py          # (re)build everything
  python3 tools/share/build-share-cards.py --check  # CI: fail if pages/cards missing or stale

Post the share/<id>.html link on Facebook, not article.html?id=...
After publishing, Facebook may cache an old preview: paste the link into
https://developers.facebook.com/tools/debug/ and press "Scrape Again".
"""
import argparse
import html
import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "share")
SITE = "https://bbowenstl-droid.github.io/ctenetwork/"
W, H = 1200, 630
GOLD, RED, INK, WHITE, GREY = (215, 168, 61), (223, 35, 54), (11, 12, 15), (255, 255, 255), (178, 182, 190)
FONT_BOLD = ["/usr/share/fonts/opentype/inter/Inter-ExtraBold.otf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"]
FONT_SEMI = ["/usr/share/fonts/opentype/inter/Inter-SemiBold.otf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]


def articles():
    raw = subprocess.check_output(["node", os.path.join(ROOT, "tools", "share", "extract-news.cjs")], cwd=ROOT)
    return json.loads(raw)


def page(a):
    url = f"{SITE}share/{a['id']}.html"
    target = f"../article.html?id={a['id']}"
    title = html.escape(a["title"].strip(), quote=True)
    desc = html.escape((a.get("subtitle") or a.get("excerpt") or "CTE Network").strip(), quote=True)
    img = f"{SITE}share/{a['id']}.jpg"
    return f"""<!DOCTYPE html>
<!-- Generated by tools/share/build-share-cards.py. Do not edit by hand. -->
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title} • CTE Network</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="{SITE}article.html?id={a['id']}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="CTE Network">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:url" content="{url}">
<meta property="og:image" content="{img}">
<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">
<meta property="og:image:alt" content="{title}">
<meta property="article:published_time" content="{html.escape(a.get('date',''))}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{title}">
<meta name="twitter:description" content="{desc}">
<meta name="twitter:image" content="{img}">
<meta http-equiv="refresh" content="0; url={target}">
<script>location.replace({json.dumps(target)});</script>
<style>body{{font:16px system-ui,-apple-system,sans-serif;background:#f5f5f7;color:#151619;display:grid;place-items:center;min-height:100vh;margin:0}}a{{color:#151619}}</style>
</head><body><main><h1>{title}</h1><p><a href="{target}">Read on CTE Network →</a></p></main></body></html>
"""


def font(paths, size):
    from PIL import ImageFont
    for p in paths:
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default(size)


def wrap(draw, text, fnt, width, max_lines):
    words, lines, cur = text.split(), [], ""
    for w in words:
        test = (cur + " " + w).strip()
        if draw.textlength(test, font=fnt) <= width:
            cur = test
        else:
            if cur:
                lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        while lines[-1] and draw.textlength(lines[-1] + "…", font=fnt) > width:
            lines[-1] = lines[-1].rsplit(" ", 1)[0] if " " in lines[-1] else lines[-1][:-1]
        lines[-1] += "…"
    return lines


def card(kicker, title, sub, date_label, path):
    from PIL import Image, ImageDraw
    img = Image.new("RGB", (W, H), INK)
    logo = Image.open(os.path.join(ROOT, "cte-league-logo.png")).convert("RGB").resize((H, H))
    # fade the logo into the background from the left
    mask = Image.new("L", (H, H))
    md = ImageDraw.Draw(mask)
    for x in range(H):
        md.line([(x, 0), (x, H)], fill=int(255 * min(1, max(0, (x - 70) / 300)) ** 1.4 * 0.9))
    img.paste(logo, (W - H + 60, 0), mask)
    d = ImageDraw.Draw(img)
    d.rectangle([60, 64, 66, 112], fill=RED)
    kf = font(FONT_SEMI, 24)
    d.text((84, 70), (kicker or "CTE NETWORK").upper()[:48], font=kf, fill=GOLD)
    size, lines = 66, []
    for size in (66, 60, 54, 48, 44):
        tf = font(FONT_BOLD, size)
        lines = wrap(d, title.upper(), tf, 640, 4)
        if not lines[-1].endswith("…") or size == 44:
            break
    y = 140
    for ln in lines:
        d.text((60, y), ln, font=tf, fill=WHITE)
        y += int(size * 1.08)
    if sub:
        sf = font(FONT_SEMI, 26)
        for ln in wrap(d, sub, sf, 640, 2):
            y += 6
            d.text((60, y + 10), ln, font=sf, fill=GREY)
            y += 34
    ff = font(FONT_BOLD, 22)
    d.text((60, H - 70), "CTE NETWORK", font=ff, fill=WHITE)
    d.text((60 + d.textlength("CTE NETWORK  ", font=ff), H - 70), "· THE LEAGUE. UNFILTERED.", font=font(FONT_SEMI, 22), fill=GREY)
    if date_label:
        d.text((60, H - 104), date_label, font=font(FONT_SEMI, 20), fill=GOLD)
    img.save(path, "JPEG", quality=84, optimize=True, progressive=True)


def nice_date(s):
    import datetime
    try:
        return datetime.date.fromisoformat(s).strftime("%B %-d, %Y").upper()
    except Exception:
        return ""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--force", action="store_true", help="re-render existing PNG cards")
    args = ap.parse_args(argv)
    items = articles()
    os.makedirs(OUT, exist_ok=True)
    problems = []
    for a in items:
        hp, ip = os.path.join(OUT, a["id"] + ".html"), os.path.join(OUT, a["id"] + ".jpg")
        want = page(a)
        if args.check:
            if not os.path.exists(hp) or open(hp, encoding="utf-8").read() != want:
                problems.append(f"stale/missing share/{a['id']}.html")
            if not os.path.exists(ip):
                problems.append(f"missing share/{a['id']}.jpg")
            continue
        with open(hp, "w", encoding="utf-8") as f:
            f.write(want)
        if args.force or not os.path.exists(ip):
            card(a.get("kicker") or a.get("category"), a["title"], a.get("subtitle") or a.get("excerpt"), nice_date(a.get("date", "")), ip)
    default = os.path.join(OUT, "cte-network.jpg")
    if args.check:
        if not os.path.exists(default):
            problems.append("missing share/cte-network.jpg")
        ids = {a["id"] for a in items}
        for f in os.listdir(OUT):
            stem, ext = os.path.splitext(f)
            if ext in (".html", ".jpg") and stem != "cte-network" and stem not in ids:
                problems.append(f"orphan share/{f}")
        if problems:
            print("Share previews out of date — run: python3 tools/share/build-share-cards.py\n  " + "\n  ".join(problems))
            return 1
        print(f"PASS: {len(items)} article share pages and cards are current")
        return 0
    if args.force or not os.path.exists(default):
        card("Official home of the CTE League", "CTE Network", "Scores, standings, trades, history and the newsroom for the CTE dynasty league.", "", default)
    print(f"Built {len(items)} share pages in share/ (cards for new articles only; --force to re-render all)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

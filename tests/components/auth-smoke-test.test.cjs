'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('auth-smoke-test.html','utf8');
const js=fs.readFileSync('js/cte-auth-smoke-test.js','utf8');
const config=fs.readFileSync('firebase-config.js','utf8');
const flag=fs.readFileSync('data/cte-participation-config.js','utf8');
assert.match(html,/name="robots" content="noindex,nofollow"/);
assert.match(html,/id="signIn"/);
assert.match(html,/id="signOut"/);
assert.match(html,/id="uid"/);
assert.match(html,/src="\.\/js\/cte-auth-smoke-test.js" type="module"/);
assert.match(js,/signInWithPopup/);
assert.match(js,/onAuthStateChanged/);
assert.match(js,/signOut\(auth\)/);
assert.match(js,/auth\/unauthorized-domain/);
assert.doesNotMatch(js,/firebase-database|\bgetDatabase\b|\bgetIdToken\b|\bfetch\s*\(/,'smoke test must not read/write data or send ID tokens');
assert.match(config,/projectId: "cte-draft-central"/);
assert.match(flag,/CTE2_CLOUD_ENABLED = false/,'shared features stay off');
console.log('PASS isolated sign-in test: no database access, no feature enablement, noindex and account verification');
